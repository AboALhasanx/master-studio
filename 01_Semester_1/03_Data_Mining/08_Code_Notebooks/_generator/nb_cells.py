CELLS.append(("md", r'''
---

# 13. Lecture §3.9 — Support Vector Regression (SVR)

> "It seeks a function that is as flat as possible while allowing errors within a tolerance ε.
> Errors outside the ε-insensitive tube are penalized. Kernel functions can represent nonlinear
> relationships."

* **ε** controls the width of the ε-insensitive region (the "tube").
* **C** controls the trade-off between model simplicity and penalties for errors outside the tube.
* The kernel choice (linear / RBF / polynomial) determines the shape of the fitted function.

The lecture's conceptual example: *house price is 250 thousand dollars and ε is 10 thousand
dollars. A prediction of 244 is inside the tolerance region → no ε-insensitive loss. A prediction of
225 is 25 away; the amount outside the tolerance region is 15 and is penalized.*

**Advantages:** nonlinear relationships via kernels, works well in high-dimensional spaces.
**Limitations:** careful tuning, **feature scaling is important**, expensive training on large data.
'''))

CELLS.append(("code", r'''
# ---------------------------------------------------------------------------------------
# Cell 13.1 - the epsilon-insensitive loss, computed by hand (the lecture's own example)
# ---------------------------------------------------------------------------------------
def epsilon_insensitive_loss(y_true, y_pred, eps):
    """L_eps = 0 if |y - y_hat| <= eps else |y - y_hat| - eps."""
    y_true = np.asarray(y_true, float); y_pred = np.asarray(y_pred, float)
    return np.maximum(0.0, np.abs(y_true - y_pred) - eps)

y_true_ex, eps = 250.0, 10.0
for pred in (244.0, 225.0):
    inside = abs(y_true_ex - pred)
    outside = max(0.0, inside - eps)
    print(f"   actual = {y_true_ex:.0f}   prediction = {pred:.0f}   |error| = {inside:.1f}   "
          f"outside the tube = {outside:.1f}   ->  eps-insensitive loss = {outside:.1f}")

print()
print("Same two cases through the function:")
print("   losses =", epsilon_insensitive_loss([250., 250.], [244., 225.], eps))
print("   (the first observation is FREE: it lies inside the tube)")

# the full SVR objective: 1/2||w||^2 + C * sum L_eps
print()
print("SVR objective:  1/2·||w||²  +  C·Σ L_eps(y_i, ŷ_i)")
print("   -> C is the price of each unit of violation; epsilon is how much violation is free.")
'''))

CELLS.append(("code", r'''
# ---------------------------------------------------------------------------------------
# Cell 13.2 - the tube, drawn
# ---------------------------------------------------------------------------------------
from sklearn.svm import SVR

rng = np.random.default_rng(RANDOM_STATE)
n = 200
xs = np.sort(rng.uniform(0, 10, n))
ys = 2.0 * xs + 5 + rng.normal(0, 0.9, n)

model = SVR(kernel="rbf", C=10.0, epsilon=1.0, gamma="scale").fit(xs.reshape(-1, 1), ys)
xs_dense = np.linspace(0, 10, 300).reshape(-1, 1)
pred = model.predict(xs_dense)

fig, ax = plt.subplots(figsize=(7.8, 4.6))
ax.scatter(xs, ys, s=18, alpha=0.6, color="#4C72B0", label="observations")
ax.plot(xs_dense.ravel(), pred, color="#C44E52", lw=2.2, label="SVR fit (RBF kernel)")
ax.fill_between(xs_dense.ravel(), pred - 1.0, pred + 1.0, color="#C44E52", alpha=0.13,
                label="ε-insensitive tube (ε = 1)")
inside = np.abs(ys - model.predict(xs.reshape(-1, 1))) <= 1.0
ax.scatter(xs[inside], ys[inside], s=52, facecolor="none", edgecolor="#2A9D8F", lw=1.5,
           label="observations inside the tube (no penalty)")
ax.set_xlabel("X"); ax.set_ylabel("y"); ax.set_title("Support Vector Regression and its ε-tube")
ax.legend(loc="upper left")
show(fig, "fig_13_01_svr_tube")

print("support vectors: %d of %d training points (%.1f%%)"
      % (len(model.support_), n, 100 * len(model.support_) / n))
print("-> the fit is carried by the points ON or OUTSIDE the tube; points inside do not")
print("   influence the solution at all (they are 'free').")
'''))

CELLS.append(("md", r'''
**Reading the figure.** The shaded band is the ε-tube. Points inside it (green rings) incur **no
loss** and therefore do not pull the function — that is the "insensitive" part of the name, and it
is why SVR is robust to small noise. Points outside the tube are penalised in proportion to how
far outside they lie. The support vectors (the points defining the tube's boundary) are the only
ones that shape the fit — a sparse, "support" set, which is the origin of the method's name and
its efficiency in high dimensions.

**Contrast with the alternatives:**
* Linear regression penalises **every** error, however small.
* SVR ignores errors **inside** the tube and penalises only the rest.
* Ridge/Lasso add a penalty on the **coefficients** instead.
'''))

