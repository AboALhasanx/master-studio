# ---------------------------------------------------------------------------------------
# Cell 5.3 — gradient descent: the same answer, found iteratively (and what the loss surface looks like)
# ---------------------------------------------------------------------------------------
def gradient_descent_ols(X, y, lr=0.05, n_iter=2000):
    X = np.asarray(X, float); y = np.asarray(y, float)
    if X.ndim == 1:
        X = X.reshape(-1, 1)
    b = np.zeros(X.shape[1] + 1)     # [intercept, slope]
    Xa = np.hstack([np.ones((X.shape[0], 1)), X])
    history = []
    for _ in range(n_iter):
        err = y - Xa @ b
        grad = -2 * Xa.T @ err / X.size
        b = b - lr * grad
        history.append(np.mean(err ** 2))
    return b, history

gd_beta, gd_hist = gradient_descent_ols(study_hours, final_mark)
print("Gradient descent solution:  ŷ = %.6f + %.6f·X" % tuple(gd_beta))
check("gradient descent == normal equation", gd_beta, beta, tol=1e-4)

# the loss surface J(b0,b1) = mean (y - b0 - b1 x)^2
b0_grid = np.linspace(30, 50, 160)
b1_grid = np.linspace(0, 10, 160)
B0, B1 = np.meshgrid(b0_grid, b1_grid)
J = np.array([[np.mean((final_mark - (b0 + b1 * study_hours)) ** 2) for b1 in b1_grid]
               for b0 in b0_grid])

