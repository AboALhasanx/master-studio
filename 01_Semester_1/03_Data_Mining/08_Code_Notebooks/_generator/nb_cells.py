CELLS.append(("code", r'''
# ---------------------------------------------------------------------------------------
# Cell 7.4 — constant-variance assumption violated: naive vs Newey–West (HAC) standard errors
# ---------------------------------------------------------------------------------------
def ols_with_se(X, y, fit_intercept=True):
    X = np.asarray(X, float); y = np.asarray(y, float)
    if fit_intercept:
        X = np.hstack([np.ones((X.shape[0], 1)), X])
    XtX_inv = np.linalg.inv(X.T @ X)
    beta = XtX_inv @ (X.T @ y)
    resid = y - X @ beta
    n, k = X.shape
    # naive (homoscedastic) covariance
    sigma2 = (resid ** 2).sum() / (n - k)
    V_naive = sigma2 * XtX_inv
    # Newey–West sandwich with Bartlett kernel and lag L = floor(4*(n/100)^(2/9))
    L = int(np.floor(4 * (n / 100) ** (2.0 / 9.0)))
    S = np.zeros((k, k))
    for t in range(n):
        u = X[t] * resid[t]
        S += np.outer(u, u)
    for l in range(1, L + 1):
        w = 1.0 - l / (L + 1.0)
        for t in range(l, n):
            u = X[t] * resid[t]; v = X[t - l] * resid[t - l]
            S += w * (np.outer(u, v) + np.outer(v, u))
    V_hac = XtX_inv @ S @ XtX_inv
    se_naive = np.sqrt(np.diag(V_naive))
    se_hac = np.sqrt(np.diag(V_hac))
    return beta, se_naive, se_hac, resid

rng = np.random.default_rng(RANDOM_STATE)
n = 400
xx = np.linspace(0, 10, n)
het = np.abs(xx) * 0.9 * rng.normal(0, 1, n)        # variance grows with x  -> heteroscedastic
yy = 4 + 1.5 * xx + het

beta, se_naive, se_hac, r = ols_with_se(xx.reshape(-1, 1), yy)
t_naive = beta[1] / se_naive[1]
t_hac = beta[1] / se_hac[1]

fig, axes = plt.subplots(1, 2, figsize=(11.4, 4.2))
axes[0].scatter(xx, r, s=14, alpha=0.6, color="#4C72B0")
axes[0].axhline(0, color="#C44E52", ls="--")
axes[0].set_xlabel("X"); axes[0].set_ylabel("residual")
axes[0].set_title("Heteroscedasticity: a funnel opens to the right")

axes[1].scatter(np.abs(r), np.full_like(r, 0), s=0)
axes[1].scatter(xx, np.abs(r), s=14, alpha=0.6, color="#4C72B0")
axes[1].set_xlabel("X"); axes[1].set_ylabel("|residual|")
axes[1].set_title("|error| grows with X — the spread is not constant")
show(fig, "fig_07_04_heteroscedasticity")

print("beta_hat (slope)      : %.4f  (true 1.5 — unbiased)" % beta[1])
print("naive  SE / t         : %.4f  /  %.2f" % (se_naive[1], t_naive))
print("HAC    SE / t         : %.4f  /  %.2f" % (se_hac[1], t_hac))
print()
print("The naive standard error is %s, so the classical t-test overstates the evidence."
      % ("too small" if se_naive[1] < se_hac[1] else "too large"))
print("HAC widens the interval -> the honest one.")
'''))

