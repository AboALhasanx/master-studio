CELLS.append(("md", r'''
**Reading the figure.** *Left:* the red line (model that omits $z$) is steeper than the truth,
because $x$ acts as a **proxy** for the omitted $z$. *Right:* $x$ and $z$ are correlated, which is
the necessary condition for the bias.

**The exact bias formula** (worth memorising, and worth the marks):

$$\text{Bias}(\hat\beta_1) \;=\; \beta_2 \cdot \frac{\operatorname{Cov}(x_1,x_2)}{\operatorname{Var}(x_1)}$$

With $\beta_2 = 5$ and $\operatorname{Cov}(x,z)/\operatorname{Var}(x) \approx 0.8$, the bias is
$5 \times 0.8 = 4$ — so the estimated slope is $2 + 4 = 6$ instead of 2. The simulation prints
the numbers; they match.

**Two exam-grade corollaries:**

1. *Correlation with the target is not enough* — a variable must be **unrelated to the error**
   (exogenous) for its coefficient to be interpretable causally.
2. If $z$ affects $y$ but is **uncorrelated** with $x$, omitting it does **not** bias $\hat\beta_1$
   (it only moves the intercept). Bias needs the *correlation* between the omitted variable and
   the included one. This is why "control for everything" can itself create problems (bad
   controls, colliders) — a modern caveat on the handout's advice.
'''))

