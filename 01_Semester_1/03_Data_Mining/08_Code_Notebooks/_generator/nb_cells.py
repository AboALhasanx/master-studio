axes[0].set_title("Least-squares loss surface J(β₀,β₁)"); axes[0].legend()

axes[1].plot(gd_hist, color="#4C72B0", lw=2)
axes[1].set_yscale("log")
axes[1].set_xlabel("iteration"); axes[1].set_ylabel("mean squared error")
axes[1].set_title("Gradient-descent convergence")
