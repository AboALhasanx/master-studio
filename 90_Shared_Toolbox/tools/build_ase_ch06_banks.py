def rotate(items: list[tuple[str, str]], correct_index: int) -> list[tuple[str, str]]:
    """Move the first, keyed pair to the desired answer slot without detaching translations."""
    return items[1:correct_index + 1] + items[:1] + items[correct_index + 1:]


def build_bank(bank: dict) -> dict:
    questions = []
    key_pattern = (LETTERS * ((len(bank["questions"]) + 3) // 4))[:len(bank["questions"])]
    for number, (raw, key) in enumerate(zip(bank["questions"], key_pattern), 1):
        concept, bloom, stem, stem_ar, correct, distractors, why, why_ar = raw
        if len(distractors) != 3:
            raise ValueError(f"{bank['id']} {concept}: expected three distractors")
        index = LETTERS.index(key)
        base_pairs = BALANCED_OPTIONS.get(concept, [correct, *distractors])
        if len(base_pairs) != 4:
            raise ValueError(f"{concept}: balanced option override must have four pairs")
        pairs = rotate(base_pairs, index)
        en = [pair[0] for pair in pairs]
        ar = [pair[1] for pair in pairs]
        questions.append({
            "id": f"q{number}", "concept_id": concept, "bloom_level": bloom,
            "question": stem, "question_ar": stem_ar,
            "options": en, "options_ar": ar, "options_en": en,
            "answer": key, "correct": index,
            "explanation": why, "explanation_ar": why_ar,
        })
    return {
        "schema_version": 2,
        "subject_id": "04_Advanced_Software_Eng",
        "subject_title": "هندسة البرمجيات",
        "semester": 1, "semester_label": "كورس أول",
        "instructor_ar": "أ.م.د. علي فاهم نعمة",
        "instructor": "Asst. Prof. Dr. Ali Fahim Ni'ma",
        "subject": "04_Advanced_Software_Eng",
        "quiz_id": f"Quiz_Ch06_{bank['id']}_{bank['slug']}",
        "topic": bank["topic"], "topic_ar": bank["topic_ar"],
        "questions": questions,
    }


def render_review(built: list[tuple[dict, dict]]) -> str:
    lines = [
        "# ASE Chapter 6 — Question Bank Review",
        "",
        "> English stems and options are shown with their Arabic counterparts. The keyed choice is marked **Correct**.",
        "> Source boundaries and corrections are documented in `Ch06_Bank_Coverage_Audit.md`.",
        "",
    ]
    for bank_meta, bank_data in built:
        lines.extend([f"## {bank_meta['id']} — {bank_meta['topic']}", "", f"Bank file: `{bank_data['quiz_id']}.json`", ""])
        for question in bank_data["questions"]:
            lines.extend([
                f"### {question['id']} · `{question['concept_id']}` · {question['bloom_level']}",
                "", question["question"], "", f"**العربية:** {question['question_ar']}", "", "| Key | English option | الخيار العربي |",
                "|:---:|:---|:---|",
            ])
            for index, (option, option_ar) in enumerate(zip(question["options_en"], question["options_ar"])):
                key = LETTERS[index]
                marker = " **Correct**" if index == question["correct"] else ""
                lines.append(f"| {key}{marker} | {option} | {option_ar} |")
            lines.extend(["", f"**Explanation:** {question['explanation']}", "", f"**ملاحظة:** {question['explanation_ar']}", ""])
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--review-out", type=Path, default=REVIEW_OUT)
    parser.add_argument("--write-review", action="store_true")
    args = parser.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    built = []
    for bank in BANKS:
        size = len(bank["questions"])
        if not 8 <= size <= 16:
            raise ValueError(f"{bank['id']} has {size} questions; every topic bank must stay within 8–16")
        data = build_bank(bank)
        path = args.out_dir / f"{data['quiz_id']}.json"
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        built.append((bank, data))
        print(f"wrote {path.name}: {size} questions; keys {data['questions'][0]['answer']}…{data['questions'][-1]['answer']}")
    if args.write_review:
        args.review_out.parent.mkdir(parents=True, exist_ok=True)
        args.review_out.write_text(render_review(built), encoding="utf-8")
        print(f"wrote review sheet {args.review_out}")


if __name__ == "__main__":
    main()
